export type DriverLanguage = 'en' | 'hi' | 'gu' | 'mr' | 'te';

export interface MilestoneStage {
  id: string;
  step: number;
  label: Record<DriverLanguage, string>;
  statusKey: string;
  iconName: string;
}

export interface ExpenseItem {
  id: string;
  timestamp: string;
  category: 'diesel' | 'dhaba' | 'puncture' | 'toll' | 'other';
  title: Record<DriverLanguage, string>;
  amount: number;
  note?: string;
}

export interface BackhaulLoadItem {
  id: string;
  commodity: Record<DriverLanguage, string>;
  weightTons: number;
  truckType: Record<DriverLanguage, string>; // Plain Highway Phrasing: Part Load vs Full Truck
  origin: string;
  destination: string;
  revenueINR: number;
  detourKm: number;
  profitScorePercent: number;
  shipperName: string;
  isAccepted?: boolean;
}

export interface CorridorCheckpoint {
  name: Record<DriverLanguage, string>;
  location: string;
  kmMark: number;
  status: 'passed' | 'current' | 'upcoming';
  tollPlaza?: string;
  tollFeeINR?: number;
}

